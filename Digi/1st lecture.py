def main():
    print("\n" + "═" * 52)
    print("        🚗  CAR SPECIFICATION LOOKUP  🚗")
    print("═" * 52)
    print("\nAvailable Cars:")
    cars_list = [
        ("1",  "Lamborghini Huracán"),
        ("2",  "Ferrari 488 GTB"),
        ("3",  "Porsche 911 Carrera S"),
        ("4",  "Bugatti Chiron Super Sport"),
        ("5",  "McLaren 720S"),
        ("6",  "Tesla Model S Plaid"),
        ("7",  "Rolls-Royce Ghost Extended"),
        ("8",  "Bentley Continental GT Speed"),
        ("9",  "Aston Martin DB11 V12"),
        ("10", "Mercedes-AMG G 63"),
    ]
    for num, name in cars_list:
        print(f"  {num:>2}.  {name}")

    print("\n" + "─" * 52)
    query = input("  Enter car name (e.g. Ferrari 488): ").strip().lower()
    print("─" * 52)

    car = CAR_DATABASE.get(query)
    if not car:
        # Build a rich search pool: DB keys + brand + model words
        query_words = set(query.replace("-", " ").split())
        best_key, best_score = None, 0
        for key, data in CAR_DATABASE.items():
            # All searchable text for this entry
            search_text = (
                key + " " +
                data["brand"].lower() + " " +
                data["model"].lower() + " " +
                data["category"].lower()
            ).replace("-", " ")
            search_words = set(search_text.split())

            # Score = number of query words found anywhere in the search text
            word_hits = sum(
                1 for w in query_words
                if any(w in sw for sw in search_words)
            )
            # Also score substring match of full query inside search text
            substring_hit = 2 if query in search_text else 0
            score = word_hits + substring_hit

            if score > best_score:
                best_score = score
                best_key = key

        if best_score > 0 and best_key:
            car = CAR_DATABASE[best_key]

    if not car:
        print(f"\n  ✗  No results for '{query}'.")
        print("  Tip: try 'ferrari 488', 'porsche 911', 'bugatti chiron', etc.\n")
        sys.exit(1)

    # Write HTML to temp file and open in browser
    html_content = generate_html(car)
    out_path = os.path.join(os.path.expanduser("~"), "car_spec_result.html")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html_content)

    print(f"\n  ✔  Opening: {car['brand']} {car['model']}")
    print(f"  ✔  File saved: {out_path}\n")
    webbrowser.open(f"file://{out_path}")


if __name__ == "__main__":
    main()